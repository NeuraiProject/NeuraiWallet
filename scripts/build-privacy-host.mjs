#!/usr/bin/env node
/**
 * Bundles the hidden privacy WebView (privacy-host/) into one HTML string.
 *
 * Hermes has no WebAssembly, so snarkjs and the C6 proving worker of
 * @neuraiproject/neurai-privacy run in a WebView. The worker is bundled first
 * and embedded in the page script, which starts it from a blob: URL; the page
 * loads nothing from the network.
 *
 * Output:
 *   blue_modules/neurai/privacy/hostHtml.generated.ts  (imported by the app)
 *   privacy-host/dist/privacy-host.html                (for browser tests)
 *
 * Usage: node scripts/build-privacy-host.mjs
 */

import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const common = {
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome90'],
  legalComments: 'none',
  logLevel: 'warning',
};

const worker = await build({ ...common, entryPoints: [join(root, 'privacy-host/worker.ts')] });
const workerSource = worker.outputFiles[0].text;

const page = await build({
  ...common,
  entryPoints: [join(root, 'privacy-host/page.ts')],
  define: { __PRIVACY_WORKER_SOURCE__: JSON.stringify(workerSource) },
});
// An inline script ends at the first `</script`, even inside a string literal.
const pageSource = page.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

// No network at all; WebAssembly compilation needs the eval keywords. Workers
// are started from blob: URLs and inherit this policy.
const csp = [
  "default-src 'none'",
  "script-src 'unsafe-inline' 'unsafe-eval' 'wasm-unsafe-eval' blob:",
  'worker-src blob:',
  "connect-src 'none'",
].join('; ');

const html =
  '<!doctype html><html><head><meta charset="utf-8">' +
  `<meta http-equiv="Content-Security-Policy" content="${csp}">` +
  '<title>Neurai privacy engine</title></head><body><script>' +
  pageSource +
  '</script></body></html>';

const sha256 = createHash('sha256').update(html).digest('hex');

const generated = join(root, 'blue_modules/neurai/privacy/hostHtml.generated.ts');
writeFileSync(
  generated,
  '/* eslint-disable */\n' +
    '// Generated by scripts/build-privacy-host.mjs from privacy-host/. Do not edit.\n' +
    `export const PRIVACY_HOST_SHA256 = '${sha256}';\n` +
    `export const PRIVACY_HOST_HTML: string = ${JSON.stringify(html)};\n`,
);

mkdirSync(join(root, 'privacy-host/dist'), { recursive: true });
writeFileSync(join(root, 'privacy-host/dist/privacy-host.html'), html);

console.log(`privacy host: ${(html.length / 1024).toFixed(0)} KiB, sha256 ${sha256}`);
